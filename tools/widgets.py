#!/usr/bin/env python3
"""Generate the widget drawables: card backgrounds per skin x shape, play buttons, scrim."""
import os

OUT = "/root/.codebuddy/artifact/2f8a7d30-9c21-4f0b-1d5c-2f4464cf5000/BunMusic/app/src/main/res/drawable"

SKINS = {
    # card fill, stroke, accent, on-accent
    "midnight": ("#1C1823", "#2A2533", "#D8F65C", "#11130A"),
    "charcoal": ("#FFFFFF", "#E6E9EE", "#171C26", "#FFFFFF"),
    "cloud":    ("#FFFFFF", "#E3EAF7", "#2E6BFF", "#FFFFFF"),
    "pink":     ("#FFFFFF", "#F7DDE6", "#D63366", "#FFFFFF"),
    "glass":    ("#C9141519", "#26FFFFFF", "#D8F65C", "#11130A"),
}

SHAPES = {"sharp": 8, "round": 20, "pill": 30}

CARD = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/widgets.py - card for the {skin} widget, {shape} corners. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <corners android:radius="{radius}dp" />
    <solid android:color="{fill}" />
    <stroke android:width="1dp" android:color="{stroke}" />
</shape>
"""

PLAY = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/widgets.py - transport button for the {skin} widget. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="oval">
    <solid android:color="{accent}" />
</shape>
"""

SCRIM = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/widgets.py - bottom scrim for the 2x2 widget. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient
        android:angle="90"
        android:startColor="#00000000"
        android:centerColor="#66000000"
        android:endColor="#D9000000" />
</shape>
"""

os.makedirs(OUT, exist_ok=True)
written = 0
for skin, (fill, stroke, accent, on) in SKINS.items():
    for shape, radius in SHAPES.items():
        path = os.path.join(OUT, f"widget_card_{skin}_{shape}.xml")
        with open(path, "w") as f:
            f.write(CARD.format(skin=skin, shape=shape, radius=radius, fill=fill, stroke=stroke))
        written += 1
    with open(os.path.join(OUT, f"widget_play_{skin}.xml"), "w") as f:
        f.write(PLAY.format(skin=skin, accent=accent))
    written += 1

with open(os.path.join(OUT, "widget_scrim.xml"), "w") as f:
    f.write(SCRIM)
written += 1

print("wrote", written, "drawables")
